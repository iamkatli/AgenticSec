"""
Central prompt library for the controlled-placement defense matrix (see
experiment_config.py for the group definitions).

VARIANTS
  "neutral" -- the element's base text. Used for every element that is not
              hardened in a given group.
  "ds"      -- neutral text + "\n\n" + POLICY_DS (data-instruction separation)
  "lp"      -- neutral text + "\n\n" + POLICY_LP (least-privilege command
              execution)
  "minimal" -- TOOL_DESCRIPTION only, used solely by the BASE_MIN
              sensitivity-check groups (see below).

CONTROLLED-PLACEMENT RULE
  A hardened element is always its own neutral text, byte-for-byte, plus
  exactly one policy block, and each policy block is ONE string reused
  verbatim at every element it is placed in (A2, T2, A3, T3, TL) -- no
  per-element rewording, including the second-person "You" (the tool
  description is read by the agent). So any difference between two groups
  that harden different elements with the same block can only come from
  WHERE the block sits. _verify_variants() asserts this at import time.

TOOL DESCRIPTION BASELINE
  TOOL_DESCRIPTION["neutral"] accurately describes the tool's real
  capability: DynamicNetworkTool runs any shell command
  (subprocess.run(shell=True)). TOOL_DESCRIPTION["minimal"] under-describes
  the same tool as a network-diagnostics tool; it exists only for the
  BASE_MIN sensitivity check ("does a narrower description alone, with
  unchanged capability, change the baseline?").

`goal` fields are fixed ("neutral") for every agent in every group.
"""

